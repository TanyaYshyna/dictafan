-- Миграция: меняем audio_order с VARCHAR(3) ('ofm', 'fom', 'mof') на VARCHAR(1)
-- Новые значения:
--   'f' — "э файл" (have audio file)
--   'm' — микрофон (microphone)
--   '' (пусто) — автоперевод (auto, первый пункт радио)
--
-- Старые значения конвертируем:
--   если первая буква 'f' → 'f'
--   если первая буква 'm' → 'm'
--   иначе → '' (пусто)

-- ============================================================
-- 1. Конвертируем существующие значения
-- ============================================================
UPDATE dictations
SET audio_order = CASE
    WHEN audio_order IS NULL OR audio_order = '' THEN ''
    WHEN LEFT(audio_order, 1) = 'f' THEN 'f'
    WHEN LEFT(audio_order, 1) = 'm' THEN 'm'
    ELSE ''
END;

-- ============================================================
-- 2. Меняем тип колонки на VARCHAR(1)
-- ============================================================
ALTER TABLE dictations
ALTER COLUMN audio_order TYPE VARCHAR(1);

-- ============================================================
-- 3. Меняем DEFAULT на пустую строку
-- ============================================================
ALTER TABLE dictations
ALTER COLUMN audio_order SET DEFAULT '';

-- ============================================================
-- 4. Обновляем комментарий
-- ============================================================
COMMENT ON COLUMN dictations.audio_order IS
'Режим озвучки: f — файл (э аудио), m — микрофон, пусто — автоперевод (авто)';
